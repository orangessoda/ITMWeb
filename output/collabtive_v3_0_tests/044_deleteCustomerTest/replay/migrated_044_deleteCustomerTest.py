import time
from selenium import webdriver
from selenium.webdriver.common.by import By
from selenium.webdriver.chrome.service import Service
CHROMEDRIVER_PATH = r"D:\chromedriver\chromedriver-win64\chromedriver-win64\chromedriver.exe"
driver_options = webdriver.ChromeOptions()
driver_options.add_argument("--window-size=1920,1080")
driver = webdriver.Chrome(service=Service(CHROMEDRIVER_PATH), options=driver_options)
driver.set_window_size(1920, 1080)
driver.get("http://collabtive-new.local:8085/")
time.sleep(1)
driver.find_element(By.XPATH, '//*[@id="username"]').clear()
driver.find_element(By.XPATH, '//*[@id="username"]').send_keys("admin")
time.sleep(1)
driver.find_element(By.XPATH, '//*[@id="pass"]').clear()
driver.find_element(By.XPATH, '//*[@id="pass"]').send_keys("admin")
time.sleep(1)
driver.find_element(By.XPATH, '//*[@id="loginform"]/fieldset/div[3]').click()
time.sleep(1)
driver.find_element(By.XPATH, '//*[@id="loginform"]/fieldset/div[4]/button').click()
time.sleep(1)
driver.find_element(By.XPATH, '//*[@id="mainmenue"]/li[3]/a').click()
time.sleep(1)
driver.find_element(By.XPATH, '//*[@id="contentwrapper"]/div[1]/ul/li[2]/a').click()
time.sleep(1)
confirm_target = driver.find_element(By.XPATH, '/html/body/div[1]/div[2]/div[2]/div/div/div[3]/div[3]/table/tbody/tr[1]/td[5]/a[2]')
driver.execute_script("window.confirm = function(){ return true; }; arguments[0].click();", confirm_target)
time.sleep(1)
driver.switch_to.default_content()
time.sleep(1)
driver.close()
time.sleep(1)
driver.quit()
time.sleep(1)
