driver.find_element(By.CSS_SELECTOR, ".preview_sql").click()
time.sleep(1)
assert driver.find_element(By.CSS_SELECTOR, ".sql").text == "INSERT INTO `testtable` (`id`, `name`) VALUES ('1', '张三'), ('2', '李四')"
time.sleep(1)
driver.find_element(By.CSS_SELECTOR, ".ui-button:nth-child(1)").click()
time.sleep(1)
driver.find_element(By.ID, "buttonYes").click()
time.sleep(1)
driver.find_element(By.LINK_TEXT, "浏览").click()
time.sleep(1)
