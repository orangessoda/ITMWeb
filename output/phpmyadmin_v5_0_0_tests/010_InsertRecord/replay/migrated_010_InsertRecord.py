time.sleep(1)
assert driver.find_element(By.CSS_SELECTOR, "tr:nth-child(1) > .text").text == "张三"
time.sleep(1)
assert driver.find_element(By.CSS_SELECTOR, "tr:nth-child(2) > .right").text == "2"
time.sleep(1)
assert driver.find_element(By.CSS_SELECTOR, "tr:nth-child(2) > .text").text == "李四"
time.sleep(1)
driver.quit()
time.sleep(1)
