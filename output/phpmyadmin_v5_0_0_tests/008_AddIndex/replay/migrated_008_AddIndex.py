from selenium import webdriver
from selenium.webdriver.common.by import By
from selenium.webdriver.support.ui import Select
import time
from selenium.webdriver.chrome.service import Service
CHROMEDRIVER_PATH = r"D:\chromedriver\chromedriver-win64\chromedriver-win64\chromedriver.exe"
driver_options = webdriver.ChromeOptions()
driver_options.add_argument("--window-size=1920,1080")
driver = webdriver.Chrome(service=Service(CHROMEDRIVER_PATH), options=driver_options)
driver.set_window_size(1920, 1080)
driver.get("http://phpmyadmin-new.local:8093/")
time.sleep(1)
driver.find_element(By.ID, "input_username").clear()
driver.find_element(By.ID, "input_username").send_keys("admin")
time.sleep(1)
driver.find_element(By.ID, "input_password").clear()
driver.find_element(By.ID, "input_password").send_keys("admin")
time.sleep(1)
driver.find_element(By.ID, "input_go").click()
time.sleep(1)
driver.find_element(By.LINK_TEXT, "test").click()
time.sleep(1)
driver.find_element(By.LINK_TEXT, "testtable").click()
time.sleep(1)
driver.find_element(By.LINK_TEXT, "结构").click()
time.sleep(1)
driver.find_element(By.NAME, "added_fields").clear()
time.sleep(1)
driver.find_element(By.NAME, "added_fields").clear()
driver.find_element(By.NAME, "added_fields").send_keys("1")
time.sleep(1)
driver.find_element(By.CSS_SELECTOR, ".btn-primary:nth-child(6)").click()
time.sleep(1)
driver.find_element(By.ID, "input_index_name").clear()
driver.find_element(By.ID, "input_index_name").send_keys("name_index")
time.sleep(1)
Select(driver.find_element(By.ID, "select_index_choice")).select_by_visible_text("INDEX")
time.sleep(1)
driver.find_element(By.CSS_SELECTOR, ".ui-button:nth-child(1)").click()
time.sleep(1)
assert driver.find_element(By.CSS_SELECTOR, ".row_span:nth-child(3) th").text == "name_index"
time.sleep(1)
driver.quit()
time.sleep(1)
