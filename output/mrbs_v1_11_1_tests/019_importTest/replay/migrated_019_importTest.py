import time
from pathlib import Path
from selenium import webdriver
from selenium.webdriver.common.by import By
from selenium.webdriver.chrome.service import Service
CHROMEDRIVER_PATH = r"D:\chromedriver\chromedriver-win64\chromedriver-win64\chromedriver.exe"
driver_options = webdriver.ChromeOptions()
driver_options.add_argument("--window-size=1920,1080")
driver = webdriver.Chrome(service=Service(CHROMEDRIVER_PATH), options=driver_options)
driver.set_window_size(1920, 1080)
driver.get("http://mrbs-new.local:8095/admin.php")
time.sleep(1)
driver.find_element(By.XPATH, '//*[@id="username"]').clear()
driver.find_element(By.XPATH, '//*[@id="username"]').send_keys("admin")
time.sleep(1)
driver.find_element(By.XPATH, '//*[@id="password"]').clear()
driver.find_element(By.XPATH, '//*[@id="password"]').send_keys("admin")
time.sleep(1)
driver.find_element(By.XPATH, '//*[@id="logon"]/fieldset[2]/div/input').click()
time.sleep(1)
driver.find_element(By.LINK_TEXT, 'Import').click()
time.sleep(1)
driver.find_element(By.XPATH, '//*[@id="upload_file"]').clear()
driver.find_element(By.XPATH, '//*[@id="upload_file"]').send_keys(str(Path(__file__).resolve().with_name("booking.ics")))
time.sleep(1)
driver.find_element(By.XPATH, '//*[@id="ignore_location"]').click()
time.sleep(1)
driver.find_element(By.XPATH, '//*[@id="area_room_create"]').click()
time.sleep(1)
driver.find_element(By.XPATH, '//*[@id="add_location"]/label[1]/input').click()
time.sleep(1)
driver.find_element(By.XPATH, '//*[@id="add_location"]/label[2]/input').click()
time.sleep(1)
driver.find_element(By.XPATH, '//*[@id="skip"]').click()
time.sleep(1)
driver.find_element(By.XPATH, '//*[@id="import"]').click()
time.sleep(1)
driver.close()
time.sleep(1)
driver.quit()
time.sleep(1)
