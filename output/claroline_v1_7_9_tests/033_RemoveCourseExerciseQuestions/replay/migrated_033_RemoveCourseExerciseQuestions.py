from selenium import webdriver
from selenium.webdriver.common.by import By
import time
from selenium.webdriver.chrome.service import Service
CHROMEDRIVER_PATH = r"D:\chromedriver\chromedriver-win64\chromedriver-win64\chromedriver.exe"
driver_options = webdriver.ChromeOptions()
driver_options.add_argument("--window-size=1920,1080")
driver = webdriver.Chrome(service=Service(CHROMEDRIVER_PATH), options=driver_options)
driver.set_window_size(1920, 1080)
driver.get("http://claroline-new.local:8089/login")
time.sleep(1)
driver.find_element(By.ID, 'username').clear()
element = driver.find_element(By.ID, 'username')
element.clear() if (element.get_attribute('type') or '').lower() != 'file' else None
element.send_keys('admin')
time.sleep(1)
driver.find_element(By.ID, "password").clear()
driver.find_element(By.ID, "password").send_keys("admin")
time.sleep(1)
driver.find_element(By.CSS_SELECTOR, 'div > div > div > form > button').click()
time.sleep(1)
driver.find_element(By.LINK_TEXT, 'John Doe').click()
driver.find_element(By.LINK_TEXT, 'Administration').click()
driver.find_element(By.LINK_TEXT, "Gestion des espaces d'activités").click()
driver.find_element(By.LINK_TEXT, 'claroline').click()
driver.find_element(By.LINK_TEXT, 'Accueil').click()
driver.find_element(By.LINK_TEXT, 'Administration').click()
time.sleep(1)
driver.find_element(By.LINK_TEXT, 'Administration').click()
driver.find_element(By.LINK_TEXT, 'Administration').click()
driver.find_element(By.LINK_TEXT, "Gestion des espaces d'activités").click()
time.sleep(1)
driver.find_element(By.XPATH, "(//img[@alt='Modify'])[1]").click()
time.sleep(1)
confirm_target = driver.find_element(By.XPATH, "/html/body/div[3]/table/tbody/tr[2]/td/a[2]/img")
driver.execute_script("window.confirm = function(){ return true; }; arguments[0].click();", confirm_target)
time.sleep(1)
assert not (("Question 1" in driver.find_element(By.TAG_NAME, "body").text))
time.sleep(1)
driver.quit()
time.sleep(1)
