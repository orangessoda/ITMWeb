from selenium import webdriver
from selenium.webdriver.common.by import By
from selenium.webdriver.support.ui import Select
import time
from selenium.webdriver.chrome.service import Service
CHROMEDRIVER_PATH = r"D:\chromedriver\chromedriver-win64\chromedriver-win64\chromedriver.exe"
driver_options = webdriver.ChromeOptions()
driver_options.add_argument("--window-size=1920,1080")
driver = webdriver.Chrome(service=Service(CHROMEDRIVER_PATH), options=driver_options)
driver.set_window_size(1920, 1080)
driver.get("http://claroline-new.local:8089/login")
time.sleep(1)
driver.find_element(By.ID, 'username').clear()
element = driver.find_element(By.ID, 'username')
element.clear() if (element.get_attribute('type') or '').lower() != 'file' else None
element.send_keys('admin')
time.sleep(1)
driver.find_element(By.ID, "password").clear()
driver.find_element(By.ID, "password").send_keys("admin")
time.sleep(1)
driver.find_element(By.CSS_SELECTOR, 'div > div > div > form > button').click()
time.sleep(1)
driver.find_element(By.LINK_TEXT, 'Administration').click()
driver.find_element(By.LINK_TEXT, 'Gestion des utilisateurs').click()
time.sleep(1)
driver.get('http://claroline-old.local:8088/claroline/admin/adminaddnewuser.php')
time.sleep(1)
element = driver.find_element(By.ID, 'username')
element.clear() if (element.get_attribute('type') or '').lower() != 'file' else None
element.send_keys('admin')
element = driver.find_element(By.ID, 'password')
element.clear() if (element.get_attribute('type') or '').lower() != 'file' else None
element.send_keys('admin')
driver.find_element(By.XPATH, "//input[@type='submit' and @value='Ok']").click()
time.sleep(float('2' or 1))
driver.get('http://claroline-old.local:8088/claroline/admin/')
driver.find_element(By.LINK_TEXT, 'Create user').click()
element = driver.find_element(By.ID, 'lastname')
element.clear() if (element.get_attribute('type') or '').lower() != 'file' else None
element.send_keys('')
time.sleep(1)
driver.find_element(By.ID, "firstname").clear()
driver.find_element(By.ID, "firstname").send_keys("")
time.sleep(1)
driver.find_element(By.ID, "username").clear()
driver.find_element(By.ID, "username").send_keys("")
time.sleep(1)
driver.find_element(By.ID, "password").clear()
driver.find_element(By.ID, "password").send_keys("")
time.sleep(1)
driver.find_element(By.ID, "password_conf").clear()
driver.find_element(By.ID, "password_conf").send_keys("")
time.sleep(1)
Select(driver.find_element(By.ID, "status")).select_by_visible_text("Follow courses")
time.sleep(1)
driver.find_element(By.CSS_SELECTOR, "input[type=submit]").click()
time.sleep(1)
assert "You left some required fields empty" == driver.find_element(By.XPATH, "//*[@id='claroBody']/table[1]/tbody/tr/td").text
time.sleep(1)
driver.quit()
time.sleep(1)
